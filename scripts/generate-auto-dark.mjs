/**
 * Generates the `prefers-color-scheme` half of the dark theme.
 *
 * `global.css` declares `color-scheme: light dark`, which tells the browser to render native
 * controls, scrollbars and form widgets in the OS theme. The tokens only answered to
 * `[data-theme="dark"]`, so on an OS in dark mode and before anything set that attribute, the
 * page had dark scrollbars on a light surface.
 *
 * `PshThemeService` does read `prefers-color-scheme` and set the attribute — the audit's
 * "0 occurrence" reads as if the OS were ignored, and it is not. What was missing is narrower
 * and still real: the stylesheet is not correct **on its own**. A consumer who imports the CSS
 * without the service gets no dark mode at all, and even with it there is a light first paint
 * under SSR, before hydration.
 *
 * The block is generated rather than written, because the alternative is 190 token
 * declarations kept in sync by hand — which is the same trap `TOKENS.md` and the class map are
 * generated to avoid. `--check` fails CI when the two drift.
 *
 * The selector is `:root:not([data-theme="light"])`: the OS preference applies unless the
 * consumer has explicitly asked for light, so an explicit choice always wins over the OS.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const THEMES = join(ROOT, 'projects/ps-helix/src/lib/styles/themes');
const SOURCE = join(THEMES, 'dark.css');
const TARGET = join(THEMES, 'dark-auto.css');

const CHECK = process.argv.includes('--check');

const src = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n');

/**
 * Everything inside the top-level `[data-theme="dark"] { … }` block.
 *
 * Read by brace depth rather than by regex: the block contains comments and nested rules, and
 * a lazy `[\s\S]*?\}` would stop at the first closing brace inside one.
 */
const open = src.indexOf('[data-theme="dark"]');
if (open === -1) throw new Error('dark.css: no [data-theme="dark"] block');

const braceStart = src.indexOf('{', open);
let depth = 0;
let braceEnd = -1;
for (let i = braceStart; i < src.length; i++) {
  if (src[i] === '{') depth++;
  else if (src[i] === '}') {
    depth--;
    if (depth === 0) {
      braceEnd = i;
      break;
    }
  }
}
if (braceEnd === -1) throw new Error('dark.css: unbalanced [data-theme="dark"] block');

const body = src.slice(braceStart + 1, braceEnd).replace(/^\n+|\n+$/g, '');
const indented = body
  .split('\n')
  .map(line => (line.trim() ? `  ${line}` : line))
  .join('\n');

const generated = `/*
 * Generated by scripts/generate-auto-dark.mjs — do not edit.
 *
 * The dark tokens again, behind the OS preference, so the stylesheet is correct without
 * PshThemeService and on the SSR first paint. \`:not([data-theme="light"])\` means an explicit
 * choice by the consumer always beats the OS.
 *
 * Edit themes/dark.css; \`npm run docs:auto-dark\` regenerates this and
 * \`npm run verify:auto-dark\` fails CI if the two have drifted.
 */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indented}
  }
}
`;

if (CHECK) {
  let current = null;
  try {
    current = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    console.error('✖ themes/dark-auto.css is missing — run npm run docs:auto-dark');
    process.exit(1);
  }
  if (current !== generated) {
    console.error('✖ themes/dark-auto.css has drifted from dark.css — run npm run docs:auto-dark');
    process.exit(1);
  }
  const count = (body.match(/--psh-[a-z0-9-]+\s*:/g) ?? []).length;
  console.log(`✔ dark-auto.css in sync — ${count} tokens behind prefers-color-scheme`);
} else {
  writeFileSync(TARGET, generated, 'utf8');
  const count = (body.match(/--psh-[a-z0-9-]+\s*:/g) ?? []).length;
  console.log(`themes/dark-auto.css written — ${count} tokens`);
}
